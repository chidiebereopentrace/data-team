def _trigger_in_blob(trigger: str, blob: str) -> bool:
    t = (trigger or "").lower().strip()
    if not t:
        return False
    if " " in t or "/" in t:
        return t in blob
    return bool(re.search(rf"\b{re.escape(t)}\b", blob, flags=re.IGNORECASE))


def enrich_decomposition_facets(
    query: str,
    decomposition: dict[str, Any] | None,
) -> dict[str, Any]:
    """
    Return a copy of decomposition with grounded entity/domain expansions.

    Only adds labels whose triggers appear in the query or existing facet strings.
    """
    out = dict(decomposition or {})
    q = (query or "").strip()
    ql = q.lower()
    entities = [str(e).strip() for e in (out.get("entities") or []) if str(e).strip()]
    domains = [str(d).strip() for d in (out.get("domains") or []) if str(d).strip()]
    existing_blob = " ".join([ql, *[e.lower() for e in entities], *[d.lower() for d in domains]])

    ent_l = {e.lower() for e in entities}
    dom_l = {d.lower() for d in domains}

    for trigger, entity, domain in _ENTITY_EXPAND:
        if not _trigger_in_blob(trigger, existing_blob):
            continue
        if entity.lower() not in ent_l:
            entities.append(entity)
            ent_l.add(entity.lower())
        if domain and domain.lower() not in dom_l:
            domains.append(domain)
            dom_l.add(domain.lower())

    out["entities"] = entities[:48]
    out["domains"] = domains[:24]
    return out


