"""Coverage ledger: every indicator class and mart object, with its disposition and readiness.

The artifact is generated by ``python -m ml.rag.helpers.build_coverage_ledger`` from the
repository contracts (class taxonomy, mart YAML, capability registry, schema cards, dbt
lineage, corpus policy and the live coverage snapshot). Planning and tests read it here.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

LEDGER_PATH = Path(__file__).resolve().parents[1] / "artifacts" / "coverage_ledger.json"

Disposition = Literal["serving", "dimension", "bridge", "unsupported"]
Readiness = Literal["discovered", "contracted", "fixture_verified", "integration_verified", "blocked"]
ColumnRole = Literal["measure", "key", "time", "geo", "filter", "lineage", "attribute", "excluded"]

READINESS_ORDER: tuple[str, ...] = (
    "blocked",
    "discovered",
    "contracted",
    "fixture_verified",
    "integration_verified",
)
OPERATIONS: tuple[str, ...] = ("lookup", "latest", "series", "compare", "rank", "categorical")


@lru_cache(maxsize=1)
def load_ledger(path: Path = LEDGER_PATH) -> dict[str, Any]:
    if not path.is_file():
        return {"classes": {}, "objects": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def table_entry(table_id: str) -> dict[str, Any] | None:
    bare = (table_id or "").strip().split(".")[-1].lower()
    entry = (load_ledger().get("objects") or {}).get(bare)
    return entry if isinstance(entry, dict) else None


def class_entry(code: str) -> dict[str, Any] | None:
    entry = (load_ledger().get("classes") or {}).get((code or "").upper())
    return entry if isinstance(entry, dict) else None


def lineage_parent(table_id: str) -> str | None:
    """The dbt fact an aggregate is built from, when the ledger records one."""
    entry = table_entry(table_id) or {}
    parent = entry.get("lineage_parent")
    return str(parent) if parent else None


def serving_tables() -> list[str]:
    objects = load_ledger().get("objects") or {}
    return sorted(t for t, e in objects.items() if isinstance(e, dict) and e.get("disposition") == "serving")


def operation_supported(table_id: str, operation: str) -> tuple[bool, str]:
    """Whether the table supports an operation, with the recorded reason when it does not."""
    entry = table_entry(table_id) or {}
    ops = entry.get("operations") or {}
    spec = ops.get(operation)
    if not isinstance(spec, dict):
        return False, "operation not recorded for table"
    return bool(spec.get("supported")), str(spec.get("reason") or "")


def min_readiness(states: list[str]) -> str:
    if not states:
        return "discovered"
    return min(states, key=READINESS_ORDER.index)


